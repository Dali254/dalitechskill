#!/usr/bin/env python3
"""Build dashboard-style skins.   python3 gen_skin.py SKINS_DIR OUT_DIR [--boost ':not(#ds-a):not(#ds-b)']

Source blocks in SKINS_DIR/<key>.css:
  @@head  raw CSS first (font @import)      @@T  tokens, both modes
  @@TL    light tokens                      @@TD dark tokens
  @@B     brand colours (skipped when <html data-ds-brand> = admin uses own theme colours)
  @@C     rules, both modes                 @@CL light-only rules     @@CD dark-only rules
In rules start each selector with "P " — it becomes html[data-ds="<key>"]<boost> (or .dark / :not(.dark)).
Output: OUT_DIR/<key>.css
"""
import os, glob, re, sys

def rules(c, pre):
    return re.sub(r'(^|[,{}]\s*|\n\s*)P ', lambda m: m.group(1) + pre + ' ', c)

def build(key, text, boost):
    parts = dict(re.findall(r'^@@(\w+)\n(.*?)(?=^@@|\Z)', text, re.S | re.M))
    root = ':root[data-ds="%s"]' % key
    pre = 'html[data-ds="%s"]%s' % (key, boost)
    css = '/* Dashboard style: %s — generated by gen_skin.py */\n' % key
    css += parts.get('head', '')
    if parts.get('T'):  css += '%s%s{%s}\n' % (root, boost, parts['T'].strip())
    if parts.get('TL'): css += '%s:not(.dark)%s{color-scheme:light;%s}\n' % (root, boost, parts['TL'].strip())
    if parts.get('TD'): css += '%s.dark%s{color-scheme:dark;%s}\n' % (root, boost, parts['TD'].strip())
    if parts.get('B'):
        raw = parts['B'].strip().rstrip(';')
        if '--sr-fg' not in raw:
            raw += ';--sr-fg-dark:color-mix(in srgb,var(--brand) 55%,#fff);--sr-fg-light:color-mix(in srgb,var(--brand) 80%,#000)'
        b = ';'.join(x.strip() + ' !important' for x in raw.split(';') if x.strip())
        css += '%s:not([data-ds-brand])%s{%s}\n' % (root, boost, b)
    css += rules(parts.get('C', ''), pre)
    if parts.get('CL'): css += rules(parts['CL'], 'html[data-ds="%s"]:not(.dark)%s' % (key, boost))
    if parts.get('CD'): css += rules(parts['CD'], 'html[data-ds="%s"].dark%s' % (key, boost))
    return css

if __name__ == '__main__':
    if len(sys.argv) < 3: sys.exit(__doc__)
    src, out = sys.argv[1], sys.argv[2]
    boost = sys.argv[sys.argv.index('--boost') + 1] if '--boost' in sys.argv else ':not(#ds-a):not(#ds-b)'
    os.makedirs(out, exist_ok=True)
    for f in sorted(glob.glob(os.path.join(src, '*.css'))):
        k = os.path.basename(f)[:-4]
        css = build(k, open(f).read(), boost)
        open(os.path.join(out, k + '.css'), 'w').write(css)
        print('%-16s %6d bytes' % (k, len(css)))
